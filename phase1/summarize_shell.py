"""Summarize the Phase 1 detailed (shell) runs: results/phase1/shell/summary.md, summary.csv and plots.

Applies the preregistered outcome rules (docs/preregistration.md Sections 3 and 9) to every run in
results/phase1/shell/runs/.
"""
import csv
import json
import sys
from pathlib import Path

import numpy as np

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "phase1" / "shell" / "runs"
OUT = ROOT / "results" / "phase1" / "shell"
PLOTS = OUT / "plots"
sys.path.insert(0, str(Path(__file__).parent))
from run_shell import P1, P2  # noqa: E402

E2_KEYS = ("E2_walkoff_79", "E2r_rocking_79", "E2_support_lost_79")


def load():
    out = {}
    for f in sorted(RUNS.glob("*.json")):
        out[f.stem] = json.loads(f.read_text())
    return out


def first_e2(ev):
    hits = [(ev[k]["T_beam"], k) for k in E2_KEYS if k in ev]
    return min(hits) if hits else None


def t_or_dash(ev, key):
    return f"{ev[key]['T_beam']:.0f}" if key in ev else "-"


def classify(r):
    """Per-run reading of the preregistered rules: E1 <= 400 C and E2 (any of E2, E2r, E2s) <= 700 C."""
    ev = r["events"]
    if r["status"] == "diverged":
        return "INCOMPLETE"
    e2 = first_e2(ev)
    peak = r["config"]["peak"]
    if e2 is not None and e2[0] <= 700.0:
        return "walk-off" if e2[0] <= 600.0 else "walk-off (600-700 C)"
    if r["status"] == "stopped":
        return "INCOMPLETE"
    return "no walk-off to %.0f C" % peak


def energy_check(rows):
    ke = np.array([x["ke"] for x in rows])
    ie = np.array([x["ie"] for x in rows])
    hg = np.array([x["hg"] for x in rows])
    ok = ie > 1.0
    ratio = np.where(ok, ke / np.maximum(ie, 1e-9), 0.0)
    return float(ratio.max()), float((ratio > 0.05).mean()), float((hg / np.maximum(ie, 1e-9))[ok].max())


def main():
    runs = load()
    if not runs:
        print("no runs")
        return
    PLOTS.mkdir(parents=True, exist_ok=True)
    order = [n for n in list(P1) + list(P2) if n in runs] + sorted(set(runs) - set(P1) - set(P2))
    head = ["Run", "Status", "Reading", "E1", "E3", "first fin", "E4", "E5", "E2 (6.25 in.)", "E2r", "E2s",
            "west plate", "max west at col 79 (in.)", "max into col 79 (in.)", "KE/IE max", "steps KE/IE > 5 %",
            "HG/IE max", "wall (h)"]
    table = []
    for n in order:
        r = runs[n]
        ev, rows = r["events"], r["rows"]
        west = max(x["lat79"] for x in rows)
        into = -min(x["ax79"] for x in rows)
        ke, frac, hg = energy_check(rows)
        table.append([n, r["status"], classify(r), t_or_dash(ev, "E1_g79_all_bolts"), t_or_dash(ev, "E3_g44_all_bolts"),
                      t_or_dash(ev, "first_fin_bolt"), t_or_dash(ev, "E4_beam_buckled"),
                      t_or_dash(ev, "E5_girder_buckled"), t_or_dash(ev, "E2_walkoff_79"),
                      t_or_dash(ev, "E2r_rocking_79"), t_or_dash(ev, "E2_support_lost_79"),
                      t_or_dash(ev, "Q12_west_plate_bearing"), f"{west:.2f}", f"{into:.2f}", f"{ke:.3f}",
                      f"{100 * frac:.1f} %", f"{hg:.3f}", f"{r['wall_s'] / 3600:.2f}"])
    with open(OUT / "summary.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(head)
        w.writerows(table)
    lines = ["# Phase 1 detailed (shell) model: results", "",
             "Generated by `phase1/summarize_shell.py` from `results/phase1/shell/runs/`. Temperatures are",
             "floor-beam temperatures (C) when the event first occurs; '-' means it did not occur. E2: lateral",
             "movement of the girder at column 79 of 6.25 in. or axial of 5.5 in. after E1 (Section 1); E2r: twist",
             ">= atan(bf/d); E2s: the girder end at column 79 has dropped 2 in. (support lost). 'west plate': the",
             "girder bears on the west side cover plate of column 79 (Q12). 'max west' is the largest movement of the",
             "girder end perpendicular to the girder toward the west; 'max into col 79' the largest movement along",
             "the girder toward the column.", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(row) + " |" for row in table]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    # plots: lateral movement at col 79 against beam temperature
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    for n in order:
        rows = runs[n]["rows"]
        T = [x["T_beam"] for x in rows]
        t = [x["t"] for x in rows]
        if n.startswith(("baseline", "mu", "Q12")):
            ax[0].plot(t, [x["lat79"] for x in rows], label=n, lw=1)
            ax[1].plot(t, [-x["ax79"] for x in rows], label=n, lw=1)
    for a, lab in zip(ax, ("west movement at col 79 (in.)", "movement toward col 79 (in.)")):
        a.set_xlabel("time (s); heating from 1.1 s, 386.7 C/s")
        a.set_ylabel(lab)
        a.grid(alpha=0.3)
    ax[0].axhline(6.25, color="k", ls="--", lw=0.8)
    ax[0].legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig(PLOTS / "col79_movement.png", dpi=130)
    plt.close(fig)
    print("\n".join(lines))


if __name__ == "__main__":
    main()

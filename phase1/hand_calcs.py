"""Phase 1 hand calculations (brief: Phase 1 step 1, column 79 check, descent check).

Writes results/phase1/hand_calcs.md and results/phase1/hand_calcs.json.
Every input comes from wtc7.assumptions, wtc7.sections or wtc7.materials.
"""
import json
import math
from pathlib import Path

import numpy as np

from wtc7 import assumptions as asm
from wtc7 import materials as mat
from wtc7.sections import col79_section, shape

OUT = Path(__file__).resolve().parents[1] / "results" / "phase1"
G = shape("W33X130")
B = shape("W24X55")
B21 = shape("W21X44")
LG, LB = 540.0, asm.value("A03")
THETA = math.radians(asm.value("A05"))
POS = asm.value("A04")                      # from col 44
WALK_LAT, WALK_AX = asm.value("A21"), asm.value("A22")
E20 = 29000.0
ALPHA = asm.value("A51")


def girder_T(tb):
    return 20.0 + 0.828 * (tb - 20.0)


def eps_th(T, model):
    return float(mat.thermal_strain(T, model))


def solve_T(target_strain, model):
    lo, hi = 20.0, 1200.0
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if eps_th(mid, model) < target_strain else (lo, mid)
    return 0.5 * (lo + hi)


def gravity():
    """Beam and girder end reactions for friction (kip). Tributary width = beam spacing."""
    w = asm.value("A34") / 1000.0 / 144.0          # ksi
    pos = np.array(POS)
    spacing = np.diff(np.concatenate([[0.0], pos, [LG]])) * math.cos(THETA)
    trib = 0.5 * (spacing[:-1] + spacing[1:])     # in., measured normal to the beams
    names = ["W21X44"] + ["W24X55"] * 4
    R_beam = w * trib * LB / 2.0                   # floor load per beam end (self-weight is in the 75 psf)
    Rg79 = sum(R * (p / LG) for R, p in zip(R_beam, pos)) + G.weight / 12000.0 * LG / 2
    Rg44 = R_beam.sum() + G.weight / 12000.0 * LG - Rg79
    return dict(w_ksi=w, trib_in=trib.tolist(), beam_names=names, R_beam=R_beam.tolist(),
                R_g79=Rg79, R_g44=Rg44)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    md, res = [], {}
    p = md.append
    p("# Phase 1 hand calculations\n")
    p("Generated by `phase1/hand_calcs.py`. Inputs are listed with their assumption IDs "
      "(see `docs/assumptions.md`). Units: in., kip, ksi, °C.\n")

    # 1. free thermal expansion
    p("## 1. Free thermal expansion\n")
    p("delta = eps_th(T) x L. NIST set: eps_th = alpha (T - 20), alpha = 1.4e-5 /°C (A51, NCSTAR 1-9 §8.7.2). "
      "EC3 set: EN 1993-1-2 Eq. 3.1a. Girder temperature from the Table 8-2 rule (A35): Tg = 20 + 0.828 (Tb - 20).\n")
    p("| Beam T (°C) | Girder T (°C) | Girder 540 in., NIST | Girder, EC3 | Beam 624 in., NIST | Beam, EC3 |")
    p("|---|---|---|---|---|---|")
    rows = []
    for tb in (100, 200, 300, 400, 500, 600, 700, 800):
        tg = girder_T(tb)
        r = [tb, tg, eps_th(tg, "NIST") * LG, eps_th(tg, "EC3") * LG, eps_th(tb, "NIST") * LB, eps_th(tb, "EC3") * LB]
        rows.append(r)
        p(f"| {tb} | {tg:.0f} | {r[2]:.2f} | {r[3]:.2f} | {r[4]:.2f} | {r[5]:.2f} |")
    res["free_expansion"] = rows
    p("\nNIST's own example (§8.7.2): 540 in. girder, ΔT = 600 °C, alpha = 1.4e-5 gives "
      f"{1.4e-5 * 600 * 540:.2f} in. (report: 4.5 in.).\n")

    # 2. kinematic requirement for lateral walk-off
    p("## 2. What beam temperature can push the girder 6.25 in. sideways at column 79?\n")
    p(f"The beams run east-west; the girder is skewed {asm.value('A05')}° from the beam-normal direction (A05), so a "
      "westward beam displacement u moves the girder node u cos(theta) perpendicular to the girder and u sin(theta) "
      "along it (toward column 79). The beam nearest column 79 meets the girder at "
      f"{POS[-1]:.0f} in. from column 44 (A04).\n")
    p("Upper bound on the girder end's lateral movement: all of the nearest beam's free elongation goes west "
      "(exterior end fully held, no slip), and the girder rotates as a rigid bar about column 44, which amplifies "
      f"the movement at column 79 by L / s = 540 / {POS[-1]:.0f} = {LG / POS[-1]:.3f}. Losses that reduce it: the "
      "clearance the beam's exterior end must close before it bears on its column (0.5 in., A27) plus seat-bolt slip.\n")
    p("| Case | Lateral movement needed at col 79 | Beam elongation needed | Beam T, NIST alpha | Beam T, EC3 |")
    p("|---|---|---|---|---|")
    cases = [("Rigid pivot about col 44, no losses", LG / POS[-1], 0.0),
             ("Girder translates with the beam (no pivot), no losses", 1.0, 0.0),
             ("Rigid pivot, 0.5 in. exterior clearance lost", LG / POS[-1], 0.5),
             ("Translation, 0.5 in. exterior clearance lost", 1.0, 0.5)]
    res["walkoff_kinematics"] = []
    for name, amp, loss in cases:
        need_beam = WALK_LAT / (amp * math.cos(THETA)) + loss
        Tn, Te = solve_T(need_beam / LB, "NIST"), solve_T(need_beam / LB, "EC3")
        res["walkoff_kinematics"].append(dict(case=name, need_beam_in=need_beam, T_nist=Tn, T_ec3=Te))
        p(f"| {name} | {WALK_LAT} in. | {need_beam:.2f} in. | {Tn:.0f} | {Te:.0f} |")
    p("\nWith the pre-errata seat (5.5 in. lateral), the rigid-pivot, no-loss case needs "
      f"{solve_T(5.5 / (LG / POS[-1] * math.cos(THETA)) / LB, 'NIST'):.0f} °C (NIST alpha).\n")
    Ts = [c[k] for c in res["walkoff_kinematics"] for k in ("T_nist", "T_ec3")]
    p(f"Reading: on beam elongation alone, lateral walk-off at column 79 needs beam temperatures of roughly "
      f"{min(Ts):.0f} °C to {max(Ts):.0f} °C, above the 400 °C at which NIST says expansion damage occurred and at or above the 600 °C "
      "end of NIST's partial-floor ramp. Things that could reduce it and must come from the models: girder bending "
      "in plan between beams, column 79 moving east (16-story model, §11.4.1), and rotation or rocking of the girder "
      "on its seat (the mechanism in Table 8-2). This bound is what the beam-element model is checked against.\n")

    # 3. restrained expansion forces vs connection capacities
    p("## 3. Force to restrain expansion against connection capacity\n")
    p("Q = A E(T) eps_th (NCSTAR 1-9 §8.7.2 Eq. 2). Bolt group capacities: 4 bolts x 45 kip = 180 kip at each girder "
      "seat; 6 x 45 = 270 kip at each fin (A07, A11).\n")
    dT_g = 180.0 / (G.A * E20 * ALPHA)
    dT_b = 270.0 / (B.A * E20 * ALPHA)
    slip = asm.value("A24") + asm.value("A25") + asm.value("A31")
    dT_g_slip = slip / (LG * ALPHA) + dT_g
    p(f"- Girder fully restrained: bolts at a seat reach 180 kip after ΔT = 180 / ({G.A} x 29000 x 1.4e-5) = "
      f"**{dT_g:.0f} °C**.")
    p(f"- With hole clearance and bolt deformation at one end ({slip:.2f} in., A24, A25, A31) taken up first: "
      f"ΔT ≈ {slip:.2f} / (540 x 1.4e-5) + {dT_g:.0f} = **{dT_g_slip:.0f} °C**, i.e. girder about "
      f"{20 + dT_g_slip:.0f} °C. NIST Table 8-2: seat bolts at col 79 failed at girder 131 °C.")
    p(f"- Floor beam fully restrained: fin bolts reach 270 kip after ΔT = {dT_b:.0f} °C.")
    p(f"- NIST's 600 °C example: Q = 38.3 x 22,235 x 1.4e-5 x 580 = {38.3 * 22235 * 1.4e-5 * 580:.0f} kip "
      "(report: about 6900 kip).\n")
    res.update(dT_girder_bolts=dT_g, dT_girder_bolts_with_slip=dT_g_slip, dT_fin=dT_b)

    # 4. studs
    p("## 4. Shear studs on the floor beams\n")
    n = asm.value("A06")["W24X55".replace("X", "x")]
    dT_s = asm.value("A13") * n / (B.A * E20 * ALPHA)
    p(f"Eq. 5 of §8.7.4 with the force shared equally by all {n} studs (A06) and slab fully restrained: studs reach "
      f"19.5 kip (A13) at ΔT = 19.5 x {n} / ({B.A} x 29000 x 1.4e-5) = **{dT_s:.0f} °C** (beam {20 + dT_s:.0f} °C). "
      "NIST Table 8-2: first stud failure at beam 103 °C. Because the end studs carry more than the average, the "
      "first failure in a model should come somewhat earlier than this.\n")
    ratio = 48 * G.Iy * LB / (B.A * LG**3)
    p(f"Girder lateral stiffness over beam axial stiffness (§8.7.4 Eq. 4): 48 Iy L1 / (A L2^3) = {ratio:.2e} "
      "(report: 2.6e-3). The girder by itself barely resists the beams' push.\n")
    res.update(dT_studs=dT_s, stiffness_ratio=ratio)

    # 5. buckling of beams and girder in plan
    p("## 5. Buckling of the floor beams and the girder in plan (20 °C, scale by E(T)/E(20) when hot)\n")
    Pb = math.pi**2 * E20 * B.Iy / LB**2
    Gsh = 11200.0
    a = B.d / 2 - B.tf / 2
    r2 = (B.Ix + B.Iy) / B.A + a**2
    Pt = (Gsh * B.J + math.pi**2 * E20 * (B.Cw + B.Iy * a**2) / LB**2) / r2
    seg = max(np.diff(np.concatenate([[0.0], POS, [LG]])))
    Pg_free = math.pi**2 * E20 * G.Iy / LG**2
    Pg_seg = min(math.pi**2 * E20 * G.Iy / seg**2, G.A * 53.6)
    p(f"- W24x55, weak-axis flexural buckling over 624 in. with no bracing: pi^2 E Iy / L^2 = **{Pb:.0f} kip**.")
    p(f"- W24x55 with its top flange held by the slab (restrained-axis torsional buckling, a = {a:.1f} in.): "
      f"(GJ + pi^2 E (Cw + Iy a^2) / L^2) / (rx^2 + ry^2 + a^2) = **{Pt:.0f} kip**.")
    p(f"- W33x130 girder, weak axis over 540 in.: {Pg_free:.0f} kip; between beams (longest segment {seg:.0f} in.): "
      f"{Pg_seg:.0f} kip (capped at squash load).")
    p(f"- E(600 °C)/E(20 °C) = {mat.E_nist(600) / mat.E_nist(20):.2f} (NIST Eq. 7).\n")
    p("Once the studs fail, a beam's resistance to buckling in plan depends almost entirely on what holds its top "
      "flange (slab contact and friction). This is why S15 is swept.\n")
    res.update(P_beam_free=Pb, P_beam_restrained=Pt, P_girder_free=Pg_free)

    # 6. gravity reactions for friction
    p("## 6. Gravity reactions (normal force for seat friction)\n")
    g = gravity()
    p(f"Floor load {asm.value('A34')} psf (A34). Beam spacing measured normal to the beams; each beam carries half "
      "of each adjacent bay, including half the distance to the column 44 and column 79 lines at the ends.\n")
    p("| Beam (north to south) | Tributary width (in.) | End reaction (kip) |")
    p("|---|---|---|")
    for nm, t, R in zip(g["beam_names"], g["trib_in"], g["R_beam"]):
        p(f"| {nm} | {t:.0f} | {R:.1f} |")
    p(f"\nGirder reaction at col 79: **{g['R_g79']:.1f} kip**; at col 44: **{g['R_g44']:.1f} kip**. "
      f"Seat friction at col 79 with mu = 0.30 (A42): {0.3 * g['R_g79']:.1f} kip.\n")
    res["gravity"] = g

    # 7. column 79
    p("## 7. Column 79 buckling with unbraced length from one to nine storeys\n")
    P = asm.value("A60")
    h = asm.value("A62")
    p(f"Axial load P = {P:.0f} kip (floor 8, gravity, §11.3.1, A60). Storey height h = {h:.0f} in. (A62). Section: "
      "W14x730 plus two 26 in. side plates (A61), 2 in. (floor 14) and 3 in. (floor 5). K = 1.0. "
      "Euler: Pe = pi^2 E I_min / (K n h)^2. Inelastic: AISC 360 Eq. E3-2/E3-3 with Fy = 50 ksi "
      "(column curve from the standard, not checked against a copy here). Columns about 300 °C at most (FAQ 11), so a "
      "300 °C case uses E(300)/E(20) from NIST Eq. 7 and the NIST first-yield ratio.\n")
    p("| Storeys unbraced | Pe, 2 in. plates | Pn, 2 in. | Pe, 3 in. plates | Pn, 3 in. | Pn, 2 in., 300 °C | Pn / P (2 in., 20 °C) |")
    p("|---|---|---|---|---|---|---|")
    res["col79"] = []
    eT = mat.E_nist(300) / mat.E_nist(20)
    fyT = mat.SteelModel("NIST", "A572").fy(300) / mat.SteelModel("NIST", "A572").fy(20)

    def aisc(A, I, L, E, Fy):
        Fe = math.pi**2 * E * I / (A * L**2)
        Fcr = Fy * 0.658 ** (Fy / Fe) if Fy / Fe <= 2.25 else 0.877 * Fe
        return Fe * A, Fcr * A

    for nst in range(1, 10):
        L = nst * h
        A2, I2, *_ = col79_section(2.0)
        A3, I3, *_ = col79_section(3.0)
        Pe2, Pn2 = aisc(A2, I2, L, E20, 50.0)
        Pe3, Pn3 = aisc(A3, I3, L, E20, 50.0)
        _, Pn2h = aisc(A2, I2, L, E20 * eT, 50.0 * fyT)
        res["col79"].append(dict(n=nst, Pe2=Pe2, Pn2=Pn2, Pe3=Pe3, Pn3=Pn3, Pn2_300=Pn2h))
        p(f"| {nst} | {Pe2:,.0f} | {Pn2:,.0f} | {Pe3:,.0f} | {Pn3:,.0f} | {Pn2h:,.0f} | {Pn2 / P:.2f} |")
    crit2 = next(r["n"] for r in res["col79"] if r["Pn2"] < P)
    crit3 = next(r["n"] for r in res["col79"] if r["Pn3"] < P)
    p(f"\nUnder gravity load alone, column 79 loses its capacity when it is unbraced over about **{crit2} storeys** "
      f"(2 in. plates) to **{crit3} storeys** (3 in. plates). At nine storeys its capacity is "
      f"{res['col79'][-1]['Pn2']:,.0f} to {res['col79'][-1]['Pn3']:,.0f} kip against {P:,.0f} kip of load, so "
      "NIST's reported nine-storey unsupported length (FAQ 9) is far more than enough for buckling. The column check "
      "does not test whether the floors fail; it confirms that if they do, the column buckles.\n")
    res.update(col79_storeys_to_fail=(crit2, crit3))

    # 8. descent kinematics
    p("## 8. Descent kinematics check (for Phase 3)\n")
    h18 = 242.0
    tff = math.sqrt(2 * h18 / 32.2)
    d2 = 0.5 * 32.2 * (4.0 - 1.75) ** 2
    p(f"Free fall over the 242 ft that the north-face roofline dropped (NCSTAR 1-9 §12.5.3): t = sqrt(2h/g) = "
      f"**{tff:.2f} s** (report 3.9 s; observed 5.4 s). Free fall over stage 2 (1.75 s to 4.0 s) from rest covers "
      f"{d2:.0f} ft; NIST reports about 105 ft (8 storeys) for that stage (NCSTAR 1A §3.6), which implies the roofline "
      f"was already moving at about {(105 - d2) / 2.25:.0f} ft/s at 1.75 s. These are the targets the Phase 3 "
      "roofline history is compared with.\n")
    res.update(t_free_fall=tff)

    (OUT / "hand_calcs.md").write_text("\n".join(md) + "\n")
    (OUT / "hand_calcs.json").write_text(json.dumps(res, indent=1, default=float))
    print("\n".join(md))


if __name__ == "__main__":
    main()

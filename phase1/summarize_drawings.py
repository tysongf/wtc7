"""Summarize the screening (plan-view) runs made with the drawings geometry.

Reads results/phase1/runs_drawings/*.json, writes results/phase1/summary_drawings.md and
results/phase1/plots/drawings_col79.png.
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "phase1" / "runs_drawings"
OUT = ROOT / "results" / "phase1"


def main():
    runs = {f.stem: json.loads(f.read_text()) for f in sorted(RUNS.glob("*.json"))}
    head = ["Run", "Friction", "Side plates", "Other", "Status", "E1", "E3", "E2 (6.25 in.)", "Max west at col 79 (in.)",
            "Max toward col 79 (in.)"]
    rows = []
    for n, r in runs.items():
        c, ev, h = r["config"], r["events"], r["rows"]
        other = []
        if c.get("history") != "monotonic":
            other.append(c["history"])
        if c.get("end79", 0.0):
            other.append(f"col 79 shifted {c['end79']:+.1f} in.")
        side = c.get("side_plates", "auto")
        rows.append([n, f"{c['mu_seat']:.2f}", "removed" if side == "clear" else "as drawn", ", ".join(other) or "-",
                     r["status"],
                     f"{ev['E1_g79_all_bolts']['T_beam']:.0f}" if "E1_g79_all_bolts" in ev else "-",
                     f"{ev['E3_g44_all_bolts']['T_beam']:.0f}" if "E3_g44_all_bolts" in ev else "-",
                     f"{ev['E2_walkoff_79']['T_beam']:.0f}" if "E2_walkoff_79" in ev
                     else f"none (peak {c['peak']:.0f} C)",
                     f"{-min(x['lat79'] for x in h):.2f}", f"{-min(x['ax79'] for x in h):.2f}"])
    rows.sort(key=lambda r: (r[3], r[2], float(r[1])))
    lines = ["# Screening model with the drawings geometry", "",
             "Plan-view model (`phase1/plan_model.py`, `geometry=drawings`, assumptions A90 to A99): girder skew",
             "16.5 deg, column 79 face 4.17 deg off square to the girder, side cover plates of column 79 as drawn",
             "(recess stop), beam stations and spans from E12/13, standard holes at the column 79 clip angle.",
             "Temperatures are beam temperatures (C); monotonic runs ramp to 800 C, heat-cool runs heat to 600 C, hold",
             "and cool to 20 C. 'Max west' is the largest movement",
             "of the girder end perpendicular to the girder, toward the west; 'max toward col 79' along the girder.",
             "Generated by `phase1/summarize_drawings.py`.", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    (OUT / "summary_drawings.md").write_text("\n".join(lines) + "\n")
    fig, ax = plt.subplots(figsize=(7, 4))
    for n, r in sorted(runs.items()):
        if r["config"].get("history") != "monotonic" or r["config"].get("end79", 0.0):
            continue
        h = r["rows"]
        side = "removed" if r["config"].get("side_plates") == "clear" else "drawn"
        ax.plot([x["T_beam"] for x in h], [-x["lat79"] for x in h], ls="--" if side == "removed" else "-", lw=1.2,
                label=f"friction {r['config']['mu_seat']:.2f}, side plates {side}")
    ax.axhline(6.25, color="k", lw=0.8, ls=":")
    ax.text(30, 6.4, "walk-off, 6.25 in.", fontsize=8)
    ax.set_xlabel("floor-beam temperature (C)")
    ax.set_ylabel("girder end at col 79, movement west (in.)")
    ax.set_ylim(-0.5, 11)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7)
    fig.tight_layout()
    (OUT / "plots").mkdir(exist_ok=True)
    fig.savefig(OUT / "plots" / "drawings_col79.png", dpi=130)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
